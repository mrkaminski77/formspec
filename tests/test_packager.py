"""Tests for multi-RDBMS init script generation and standalone Docker bundle packager."""

from __future__ import annotations

import json
from pathlib import Path
import sqlite3
import tempfile
import unittest
import zipfile

from formspec.generators.db_init import (
    PostgresDialect,
    generate_db_init_sql,
    list_dialects,
    register_dialect,
)
from formspec.ide.server import IDEApp


def _extract_token(set_cookie_header: str) -> str:
    return set_cookie_header.split(";", 1)[0].split("=", 1)[1]


class CustomOracleLikeDialect(PostgresDialect):
    id = "custom_test_rdbms"
    label = "Custom Test RDBMS"
    description = "Extensible test dialect"


class PackagerTests(unittest.TestCase):
    def test_multi_rdbms_init_scripts_and_zip_docker_bundle(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            tmp_dir = Path(tmp)
            db_path = tmp_dir / "pkg_studio.db"
            pkg_root = tmp_dir / "bundles"
            app = IDEApp(
                dsn=f"sqlite:///{db_path}",
                secret="pkg-sec",
                package_staging_dir=pkg_root,
            )
            try:
                _, _, cookie = app.handle_api(
                    "POST",
                    "/api/auth/setup",
                    {"username": "superuser", "password": "strong-password-123"},
                )
                token = _extract_token(cookie or "")

                # Create parent & child domain entities with FK, permission, and forms
                app.handle_api(
                    "POST",
                    "/api/entities",
                    {
                        "name": "department",
                        "label": "Department",
                        "attributes": [{"name": "name", "fspec_type": "text", "nullable": False}],
                    },
                    session_token=token,
                )
                app.handle_api(
                    "POST",
                    "/api/entities",
                    {
                        "name": "employee",
                        "label": "Employee",
                        "attributes": [
                            {"name": "full_name", "fspec_type": "text", "nullable": False},
                            {"name": "department_id", "fspec_type": "int", "nullable": True, "fk_table": "department"},
                        ],
                    },
                    session_token=token,
                )
                app.handle_api(
                    "POST",
                    "/api/forms/from-entity",
                    {"entity": "employee", "form_type": "detail"},
                    session_token=token,
                )

                # Dialects API lists sqlite, postgres, mysql, mssql and allows extensions
                _, d_res, _ = app.handle_api("GET", "/api/package/dialects", session_token=token)
                dialect_ids = [d["id"] for d in d_res["dialects"]]
                self.assertEqual(dialect_ids[:4], ["sqlite", "postgres", "mysql", "mssql"])

                # Test SQL generation for all 4 dialects + custom dialect registration
                with app.open_adapter() as adp:
                    sqlite_sql = generate_db_init_sql(adp, "sqlite")
                    pg_sql = generate_db_init_sql(adp, "postgres")
                    mysql_sql = generate_db_init_sql(adp, "mysql")
                    mssql_sql = generate_db_init_sql(adp, "mssql")

                    self.assertIn("INTEGER PRIMARY KEY AUTOINCREMENT", sqlite_sql)
                    self.assertIn("GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", pg_sql)
                    self.assertIn("pg_get_serial_sequence", pg_sql)
                    self.assertIn("AUTO_INCREMENT PRIMARY KEY", mysql_sql)
                    self.assertIn("ENGINE=InnoDB", mysql_sql)
                    self.assertIn("IDENTITY(1,1)", mssql_sql)
                    self.assertIn("NVARCHAR(255)", mssql_sql)
                    self.assertIn("SET IDENTITY_INSERT [roles] ON;", mssql_sql)

                    # Parent entity `department` precedes child entity `employee`
                    self.assertLess(
                        pg_sql.index('CREATE TABLE "department"'),
                        pg_sql.index('CREATE TABLE "employee"'),
                    )

                    # Execute SQLite SQL in fresh DB and verify schema, roles, permissions & forms exist
                    fresh_conn = sqlite3.connect(":memory:")
                    fresh_conn.executescript(sqlite_sql)
                    role_names = {r[0] for r in fresh_conn.execute("SELECT name FROM roles").fetchall()}
                    self.assertEqual(role_names, {"admin", "guest", "anon"})
                    perm_names = {p[0] for p in fresh_conn.execute("SELECT name FROM permissions").fetchall()}
                    self.assertIn("employee:write", perm_names)
                    form_names = {f[0] for f in fresh_conn.execute("SELECT name FROM forms").fetchall()}
                    self.assertEqual(form_names, {"home", "employee_form"})
                    fresh_conn.close()

                register_dialect(CustomOracleLikeDialect())
                self.assertIn("custom_test_rdbms", [d["id"] for d in list_dialects()])

                # Package standalone web app via IDE API targeting PostgreSQL
                code, pkg_res, _ = app.handle_api(
                    "POST",
                    "/api/package",
                    {
                        "app_name": "HR Portal",
                        "dialect": "postgres",
                        "include_data": False,
                        "build_docker": False,
                    },
                    session_token=token,
                )
                self.assertEqual(code, 201)
                self.assertEqual(pkg_res["app_name"], "hr-portal")
                self.assertEqual(pkg_res["init_sql_filename"], "init_db.postgres.sql")

                bundle = app.packager.get_bundle(pkg_res["bundle_id"])
                assert bundle is not None
                self.assertTrue(bundle.zip_path.is_file())

                with zipfile.ZipFile(bundle.zip_path, "r") as zf:
                    names = set(zf.namelist())
                    self.assertIn("Dockerfile", names)
                    self.assertIn("docker-compose.yml", names)
                    self.assertIn("app_data/init_db.postgres.sql", names)
                    self.assertIn("app_data/init_db.sqlite.sql", names)
                    self.assertIn("app_data/manifest.json", names)
                    self.assertIn("formspec/runtime/server.py", names)
                    self.assertFalse(any(n.startswith("formspec/ide/static/") for n in names))

                    dockerfile = zf.read("Dockerfile").decode("utf-8")
                    self.assertIn('CMD ["python3", "-m", "formspec", "app"]', dockerfile)
                    self.assertNotIn('CMD ["python3", "-m", "formspec", "ide"]', dockerfile)

                    manifest = json.loads(zf.read("app_data/manifest.json").decode("utf-8"))
                    self.assertEqual(manifest["dialect"], "postgres")
                    self.assertEqual(manifest["entry_form"], "home")
            finally:
                app.packager.cleanup()
                app.git.cleanup()


if __name__ == "__main__":
    unittest.main()
